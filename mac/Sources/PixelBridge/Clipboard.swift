import AppKit
import CryptoKit

/// Polls the general pasteboard (macOS has no change notification) and reports new local copies.
final class ClipboardWatcher {
    enum Content {
        case text(String)
        case image(Data) // PNG
    }

    private let pb = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var lastRemoteHash: String?
    var onLocalCopy: ((Content) -> Void)?

    /// Password managers mark secrets with these (see nspasteboard.org); never sync them.
    private let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    init() { lastChangeCount = pb.changeCount }

    func start() {
        timer?.invalidate()
        lastChangeCount = pb.changeCount
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func currentContent() -> Content? {
        let types = Set((pb.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: skipTypes) { return nil }
        if let s = pb.string(forType: .string), !s.isEmpty { return .text(s) }
        if let png = pb.data(forType: .png) { return .image(png) }
        if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return .image(png)
        }
        return nil
    }

    private func poll() {
        let cc = pb.changeCount
        guard cc != lastChangeCount else { return }
        lastChangeCount = cc
        guard let content = currentContent() else { return }
        // Don't bounce back what the phone just sent us.
        if hash(content) == lastRemoteHash { return }
        onLocalCopy?(content)
    }

    /// Puts content from the phone on the Mac clipboard without echoing it back.
    func setFromRemote(_ content: Content) {
        lastRemoteHash = hash(content)
        pb.clearContents()
        switch content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let png):
            pb.setData(png, forType: .png)
            if let img = NSImage(data: png), let tiff = img.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        }
        lastChangeCount = pb.changeCount
    }

    private func hash(_ c: Content) -> String {
        let d: Data
        switch c {
        case .text(let s): d = Data(s.utf8)
        case .image(let png): d = png
        }
        return SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined()
    }
}
